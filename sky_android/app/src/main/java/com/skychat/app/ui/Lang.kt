/** The app's language. Reading [bn] inside a screen makes the screen update when the language is changed. */
object L {
    var bn by mutableStateOf(false)
    /** [pref]: "system" (follow the phone), "en" or "bn". */
    fun apply(pref: String) { val v = when (pref) { "bn" -> true; "en" -> false; else -> java.util.Locale.getDefault().language == "bn" }; if (v != bn) bn = v }
}

/** Translates an English text of the screens into Bengali when the language is Bengali; any text without a translation stays English. */
fun t(en: String): String = if (L.bn) (BN[en] ?: en) else en

